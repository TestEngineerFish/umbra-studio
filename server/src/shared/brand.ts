/** 这个产品的 ASCII 全名，**只给文件系统用**（安装包文件名、`.app` 名若将来改）。
 *
 *  ⚠️ **为什么文件名不用中文**：win 的分发物是 `.zip`，而本仓库
 *  `ziptest` 钉着一条实测教训 —— 中文文件名在严格解压方那边要靠 bit 11，
 *  不是所有解压器都认。分发物的文件名用 ASCII 是**少一类不会在本机暴露的故障**。
 *  ⚠️ 代价照实说：英文名还是占位，定下来要改这里一行，而那会改掉下一版安装包的文件名。
 *  安装包是一次性的分发物（不留在用户的 `/Applications` 里），所以改它不留孤儿。 */
export const studioNameEn = `${productNameEn} Studio`;

/** **`Info.plist` 那两个键（`CFBundleDisplayName` / `CFBundleName`）显示的名字。**
 *
 *  ⚠️⚠️ **2026-10-23 改名 + 改语义，而「改语义」才是重点。**
 *  它原来叫 `displayNameEn`，注释写着「英文环境下显示的产品名」，
 *  而 `shell/package.json` 里 `CFBundleDisplayName` **只有一份、所有语言环境共用**
 *  —— 没有 `.lproj` / `InfoPlist.strings` 分语言。
 *  所以那个名字说的是一件**不成立的事**：它不是「英文那一份」，它是「唯一那一份」。
 *
 *  geek-99 2026-10-23 的两条指示在这个事实下**互相矛盾**：
 *  「`displayNameEn` 改为指向 `productNameEn`」+「只有一份就保持长尾雀」——
 *  两条一起做会让 `captest` 那条 `CFBundleDisplayName === displayNameEn` 的对账判据必红，
 *  而且会让这个常量**失去它唯一的消费者**（那正是本项目栽过的形状：
 *  `buildIndex` 往项目里拷 `select-bridge.js`，而读它的人是零个）。
 *  > **一个常量指向一个没人读的值，比没有这个常量更坏** —— 它让下一个人以为改它有用。
 *
 *  所以按 geek-99 那条**带条件的**指示执行（只有一份 → 保持中文名），
 *  并把名字改对：**它是 bundle 的显示名，不分语言**。
 *  ⚠️ **2026-10-24（M17-1）分语言做掉了**，而这个常量的语义**没变**：
 *  它仍然是 `Info.plist` 里那一份，也就是**兜底值** —— 没有被 `.lproj` 覆盖的语言看它。
 *  分语言那张表在下面 `bundleDisplayNameByLocale`。 */
export const bundleDisplayName = studioName;

/** **按系统语言显示的 bundle 名**（M17-1，2026-10-24）。
 *  `afterPack` 据此往 `.app/Contents/Resources/<语言>.lproj/InfoPlist.strings` 里写
 *  `CFBundleDisplayName` / `CFBundleName`，Finder / Dock / 关于面板按用户的语言取。
 *
 *  ### ⚠️⚠️ 兜底值为什么留中文，而不是换成英文
 *  判据是**哪一种失败更糟**，不是「哪个更规范」：
 *  · 兜底换英文 → 万一 `.lproj` 这条路不生效（目录名对不上、签名把它剥掉、
 *    以后 Electron 改了语言目录名…），**中文用户会看到英文**，比今天差；
 *  · 兜底留中文 → 不生效时**和今天完全一样**，生效时英文系统拿到英文。
 *  而这条路**在改名的人手上验不了**：要真改系统语言才看得见，那是用户的系统设置。
 *  > **一个只能在别人的机器上才看得见的改动，要把它的失败模式选成「和今天一样」。**
 *
 *  ### ⚠️ 语言目录名用 Electron 自己声明的那几个
 *  实测上一次的真产物里有 **55 个 `.lproj`**（Chromium 的语言包），中英文是
 *  `zh_CN` / `zh_TW` / `en` / `en_GB` —— **都是空目录**。写进它自己声明的那几个，
 *  而不是另造 `zh-Hans.lproj`：`CFBundle` 认 `zh_CN` 这种旧式名，而
 *  **一个应用「有哪些语言」是按 `.lproj` 目录名算的** —— 另造一个等于多声明一种语言。
 *  ⏳ `zh_TW` 这一份写的是**简体的「长尾雀」**，也就是今天那些用户看到的东西。
 *  繁体该写「長尾雀」还是别的，**是一个起名决定，不是一个实现决定** —— 留给 sam / geek-99。
 *  在它定之前照原样，**不自己发明一个繁体名**。 */
export const bundleDisplayNameByLocale: Readonly<Record<string, string>> = {
  en: studioNameEn,
  en_GB: studioNameEn,
  zh_CN: studioName,
  zh_TW: studioName,
};

/** **冻结的应用身份名** —— 它决定 `.app` 的文件名、`userData` 目录、TCC 授权与钥匙串归属。
 *
 *  ⚠️⚠️ **这一个不跟着改名动，永远。** 理由写在 `shell/package.json` 的 `_品牌说明` 里：
 *  改了它，用户 `/Applications` 里会多一个孤儿，**已装的数据也会失联**
 *  （userData 换了目录 = 登录、最近打开、插件、快照全部「不见了」）。
 *  所以它和 `appId`（`com.umbrastudio.app`）是同一类东西：**身份，不是称呼。**
 *
 *  ⚠️ **为什么要在这里有一份**：2026-10-23 `captest` 那道品牌闸抓到
 *  `plaintest.ts` 里硬写了一个 `"Umbra Studio"` 去拼 userData 路径 —— 而那个值**是对的**。
 *  闸抓的不是值错，是**来源错**：一个「值对了但硬写着」的串，下次改名时照样过期，
 *  而**没有任何东西会提醒**。
 *  > **把「这个值为什么不能改」写在它旁边，比把它写对一次更有用。**
 *
 *  显示给人看的名字一律走 `studioName` / `bundleDisplayName`，**不读这一个**。 */
export const appIdentityName = "Umbra Studio";

