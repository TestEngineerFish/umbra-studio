/** 品牌名的**唯一来源**（sam 2026-10-22 拍板，geek-99 转达）。
 *
 *  ### 为什么要有这个文件
 *  对外产品名从「Umbra」改成「**长尾雀**」，而 `Umbra` 留作内部代号。
 *  改名这件事的全部风险不在「替换字符串」，在**哪些 `Umbra` 不是品牌名** ——
 *  实测全仓 `Umbra` 出现 400+ 次，其中绝大多数是**标识符**
 *  （`UMBRASTUDIO_*` 环境变量 · `.umbrastudio/` 目录 · `com.umbra.*` 插件 id ·
 *  `umbradesign-app` postMessage 源 · `X-Umbra-Src` 协议头 · `data-ud-node`）。
 *  **这些一个都不改** —— 它们是协议和数据的一部分，改了就是不兼容。
 *
 *  ### ⚠️⚠️ 三个名字，不是一个
 *  这是这次收口里最容易搞错的一件事，所以用三个常量把它显式分开：
 *
 *  | 常量 | 指什么 | 例子 |
 *  | --- | --- | --- |
 *  | `studioName` | **这个产品**（本仓库做的东西） | 窗口标题、关于、首页顶栏 |
 *  | `platformName` | **账号与服务那一族**（跨仓库） | 「Umbra 账号」「Umbra 服务端」「Umbra PC / iOS」 |
 *  | `codename` | 内部代号，只出现在注释和标识符里 | `com.umbra.markdown` |
 *
 *  ⚠️ **`platformName` 现在仍是 `Umbra`，这是有意的**：设置页那句「和 Umbra PC、iOS
 *  用同一个账号」、市场页那句「没连上 Umbra 服务端」说的都**不是本产品** ——
 *  账号中心（passport）、PC、iOS 各在自己的仓库里，它们对外叫什么**本仓定不了**。
 *  在这里单方面改成「长尾雀账号」，用户就会拿着一个叫「长尾雀」的账号去一个写着
 *  「Umbra」的 PC 端登录。
 *  > **一个跨仓库的名字，在任何一个仓库里单方面改，都是制造不一致而不是消除它。**
 *  三端都定了之后，改这**一行**即可。
 *
 *  ### 中文间距规则（geek-99 2026-10-22，全端统一）
 *  「长尾雀」挨着**汉字或中文标点**时**不留空格**，挨着**英文或数字**时留**一个**空格。
 *  所以是「长尾雀 Studio」（接英文）、「长尾雀账号」（接汉字，**不是**「长尾雀 账号」）。
 *  ⚠️ 原来给 `Umbra` 留的空格是因为它本身是英文词，换成汉字之后那个空格就是错的。
 *  **这条规则有判据钉着**（`captest` ⑯），不靠人记 ——
 *  `/长尾雀[ ]+[汉字或中文标点]/` 命中一律红。
 *
 *  ### 这个文件为什么住在 `shared/`
 *  `server/src/shared/` 是前后端共用的纯 TS（本文件 **import 零个东西**，遵守那条纪律）。
 *  前端经 vite 别名 `@shared/brand` 拿，服务端直接相对 import。
 *  ⚠️ **两种消费者 import 不了 TS**：`shell/package.json`（electron-builder 的构建配置）
 *  和 `app/index.html`（首屏 `<title>`）。那两处只能是字面量，
 *  **由 `captest` 的判据钉死它们等于这里的派生值** —— 对账而不是复制。
 */

/** 对外产品名（中文，已定）。 */
export const productName = "长尾雀";

