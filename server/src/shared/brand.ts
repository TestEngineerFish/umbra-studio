export const studioName = `${productName} Studio`;

/** 这个产品的 ASCII 全名，**只给文件系统用**（安装包文件名、`.app` 名若将来改）。
 *
 *  ⚠️ **为什么文件名不用中文**：win 的分发物是 `.zip`，而本仓库
 *  `ziptest` 钉着一条实测教训 —— 中文文件名在严格解压方那边要靠 bit 11，
 *  不是所有解压器都认。分发物的文件名用 ASCII 是**少一类不会在本机暴露的故障**。
 *  ⚠️ 代价照实说：英文名还是占位，定下来要改这里一行，而那会改掉下一版安装包的文件名。
 *  安装包是一次性的分发物（不留在用户的 `/Applications` 里），所以改它不留孤儿。 */
export const studioNameEn = `${productNameEn} Studio`;

/** **英文环境下显示的产品名。** 现在刻意等于中文名（sam 2026-10-22）。
 *
 *  英文名定下来之后**只改这一行**指向 `productNameEn` —— 这就是这个字段存在的全部理由：
 *  让「英文环境显示什么」成为**一处开关**，而不是散在英文文案、Info.plist、
 *  权限说明、邮件模板里的几十处判断。
 *  ⚠️ 本仓库界面是中文的，所以今天它的消费者是 **Info.plist**
 *  （`CFBundleDisplayName` / `CFBundleName` —— 英文系统的 Finder / Dock 读这两个）。
 *  它**不等于** `studioNameEn`：后者是文件名用的 ASCII 串，前者是给人看的。 */
export const displayNameEn = `${productName} Studio`;

/** 账号与服务那一族的名字（账号中心 / PC / iOS / Android / 服务端 / Console / 官网）。
 *
 *  ⚠️ **值是派生的，不是字面量** —— geek-99 2026-10-22 确认整个家族一起改名
 *  （PC #130 · iOS #97 · 服务端 #139「你的长尾雀账号」· Android / Console / 官网，PR 都开着一起合）。
 *  那它为什么还要单独存在、而不是让那三十来处直接用 `productName`？
 *  因为**它回答的是另一个问题**：那些话说的是「账号与服务那一族」而不是「本产品」。
 *  哪天家族名和产品名再次分开（并购、子品牌、Studio 独立发行），
 *  要改的是这一行，而不是去三十处里逐个判断「这句说的是谁」——
 *  而那个判断**正是这次收口最花时间的部分**，不该让下一个人再做一遍。
 *  > **把一次判断的结果存成一个名字，比把判断留给下一个人可靠。** */
export const platformName = productName;
